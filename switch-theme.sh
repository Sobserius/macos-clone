#!/usr/bin/env bash
# switch-theme.sh — Meadow light/dark switching.
# Usage: switch-theme [light|dark|toggle|auto] [--force]
#
# Port of the dark-notify + switch-theme.sh from
# https://github.com/gloceandotdev/dotfiles
set -euo pipefail

DOTFILES="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_DIR="$CONFIG/meadow"
STATE_FILE="$STATE_DIR/state"
SETTINGS="$STATE_DIR/config"

MODE="auto"
FORCE=0

usage() {
    cat <<'EOF'
Usage: switch-theme [light|dark|toggle|auto] [--force]

  light    apply Meadow Light
  dark     apply Meadow (dark)
  toggle   invert the current theme
  auto     follow the schedule in ~/.config/meadow/config (default)

  --force  apply even if the theme is already active
EOF
}

for arg in "$@"; do
    case "$arg" in
        light | dark | toggle | auto) MODE="$arg" ;;
        --force) FORCE=1 ;;
        -h | --help) usage; exit 0 ;;
        *)
            echo "switch-theme: unknown argument: $arg" >&2
            usage >&2
            exit 1
            ;;
    esac
done

# ── Settings ──────────────────────────────────────────────────────────────────
LIGHT_FROM="07:00"
DARK_FROM="19:00"
LAT=""
LON=""
if [ -f "$SETTINGS" ]; then
    # shellcheck disable=SC1090
    . "$SETTINGS"
fi

current_mode() {
    if [ -f "$STATE_FILE" ]; then
        tr -d '[:space:]' <"$STATE_FILE"
    else
        echo "dark"
    fi
}

is_day() {
    if [ -n "$LAT" ] && [ -n "$LON" ] && command -v python3 >/dev/null 2>&1; then
        [ "$(python3 "$DOTFILES/lib/sun.py" "$LAT" "$LON")" = "day" ]
        return
    fi

    local now light dark
    now=$((10#$(date +%H%M)))
    light=$((10#${LIGHT_FROM//:/}))
    dark=$((10#${DARK_FROM//:/}))

    if [ "$light" -le "$dark" ]; then
        [ "$now" -ge "$light" ] && [ "$now" -lt "$dark" ]
    else
        # window wraps midnight, e.g. LIGHT_FROM=20:00 DARK_FROM=06:00
        [ "$now" -ge "$light" ] || [ "$now" -lt "$dark" ]
    fi
}

apply_theme() {
    local mode="$1"
    local palette="meadow"
    local gtk_scheme="prefer-dark"
    local portal_scheme="uint32 1"
    local ghostty_theme="Meadow"
    local current

    current="$(current_mode)"
    if [ "$current" = "$mode" ] && [ "$FORCE" -eq 0 ]; then
        exit 0
    fi

    mkdir -p "$STATE_DIR"
    printf '%s\n' "$mode" >"$STATE_FILE"

    if [ "$mode" = "light" ]; then
        palette="meadow-light"
        gtk_scheme="prefer-light"
        portal_scheme="uint32 2"
        ghostty_theme="Meadow Light"
    fi

    # Starship (both palettes live in starship.toml, as upstream)
    if [ -f "$CONFIG/starship.toml" ]; then
        sed -i --follow-symlinks -E \
            "s/^palette = .*/palette = \"${palette}\"/" \
            "$CONFIG/starship.toml"
    fi

    # Fish (colors generated from fish/themes/Meadow.theme)
    local fish_conf="$CONFIG/fish/conf.d/90-meadow-theme.fish"
    if [ -f "$DOTFILES/fish/themes/Meadow.theme" ]; then
        mkdir -p "$(dirname "$fish_conf")"
        {
            echo "# Generated by switch-theme.sh — do not edit."
            awk -v want="[$mode]" '
                /^\[/ { in_section = ($0 == want); next }
                in_section && /^fish_/ { print "set -g " $0 }
            ' "$DOTFILES/fish/themes/Meadow.theme"
        } >"$fish_conf"
    fi

    # Ghostty: explicit theme file so switching does not depend on the portal.
    local ghostty_conf="$CONFIG/ghostty/theme.conf"
    if [ -d "$CONFIG/ghostty" ]; then
        printf 'theme = %s\n' "$ghostty_theme" >"$ghostty_conf"
        pkill -USR2 -x ghostty >/dev/null 2>&1 || true
    fi

    # GTK / desktop portal appearance
    if command -v gsettings >/dev/null 2>&1; then
        gsettings set org.gnome.desktop.interface color-scheme "$gtk_scheme" >/dev/null 2>&1 || true
    fi
    if command -v gdbus >/dev/null 2>&1; then
        gdbus call --session \
            --dest org.freedesktop.portal.Desktop \
            --object-path /org/freedesktop/portal/desktop \
            --method org.freedesktop.portal.Settings.Set \
            org.freedesktop.appearance color-scheme "<${portal_scheme}>" \
            >/dev/null 2>&1 || true
    fi
    pkill -HUP -x xsettingsd >/dev/null 2>&1 || true

    # AwesomeWM: pick up palette + wallpaper
    if [ -n "${DISPLAY:-}" ] && command -v awesome-client >/dev/null 2>&1; then
        awesome-client 'awesome.restart()' >/dev/null 2>&1 || true
    fi

    echo "Meadow: ${mode}"
}

case "$MODE" in
    light | dark)
        FORCE=1
        apply_theme "$MODE"
        ;;
    toggle)
        if [ "$(current_mode)" = "light" ]; then
            FORCE=1
            apply_theme dark
        else
            FORCE=1
            apply_theme light
        fi
        ;;
    auto)
        if is_day; then
            apply_theme light
        else
            apply_theme dark
        fi
        ;;
esac
